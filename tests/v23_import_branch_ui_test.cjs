const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict'),path=require('path');
const root=path.resolve(__dirname,'../web');
const engine=fs.readFileSync(path.join(root,'engine.js'),'utf8');
const importer=fs.readFileSync(path.join(root,'importer.js'),'utf8');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
const from=engine.indexOf('function safeText('),to=engine.indexOf('function chunkFor(');
assert.ok(from>=0&&to>from);
const c=vm.createContext({Date,Number,Object,Math,Array,String,now:()=>new Date('2026-11-08').toISOString()});
vm.runInContext(engine.slice(from,to),c);
assert.equal(c.sourcePin({pinned:true}),true);
assert.equal(c.sourcePin({settings:{isPinned:1}}),true);
assert.equal(c.sourcePin({pinned:false}),false);
assert.equal(c.sourceTime(1762550000000),new Date(1762550000000).toISOString());
const shaped=c.toSessionShape({id:'x',is_pinned:true,createdAt:'2026-04-02',updatedAt:'2026-05-09'},'chatbox:x');
assert.equal(shaped.pinned,true);assert.equal(shaped.updatedAt,new Date('2026-05-09').toISOString());
const old={id:'one',role:'assistant',content:'旧回复',createdAt:'2026-01-01'};
const other={id:'two',role:'assistant',content:'另一个回复',createdAt:'2026-01-02'};
const normalized=c.normalizeMessage({id:'m1',role:'assistant',alternatives:[old,other],select_index:1},'chatbox:x',9);
assert.equal(normalized.branchVariants.length,2);assert.equal(normalized.branchIndex,1);assert.equal(normalized.content,'另一个回复');
const ic=vm.createContext({Engine:{sourcePin:c.sourcePin,sourceTime:c.sourceTime}});vm.runInContext(importer+"\nthis.Importer=Importer;",ic);
const imported=ic.Importer.fromNode({id:'a',select_index:1,node_index:5,messages:[{id:'r1',role:'assistant',parts:[{type:'text',text:'第一版'}],createdAt:1762550000000},{id:'r2',role:'assistant',parts:[{type:'text',text:'第二版'}],createdAt:1762550001000}]},'rikka:conv',0);
assert.equal(imported.branchVariants.length,2);assert.equal(imported.content,'第二版');assert.equal(imported.branchIndex,1);
for(const key of ['switch-message-branch','regenerate-message','copy-message','quote-message','delete-message','session-menu:','message-avatar-column','branch-controls'])assert.ok(app.includes(key),'missing '+key);
assert.ok(css.includes('.message-avatar-column')&&css.includes('.message-actions'));
assert.ok(engine.includes('if(regenTarget)')&&engine.includes('branchVariants=variants'));
for(const name of ['engine.js','importer.js','app.js','styles.css'])assert.equal(fs.readFileSync(path.join(root,name),'utf8'),fs.readFileSync(path.join(__dirname,'../app/src/main/assets',name),'utf8'));
console.log('PASS v2.3: original date/pin, Rikka & Chatbox branches, per-message actions, long-press drawer, avatar layout, asset synchronization');
